CREATE TABLE attendances
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    employee_id     BIGINT                                  NOT NULL,
    attendance_date date                                    NOT NULL,
    check_in        TIMESTAMP(6) WITH TIME ZONE,
    check_out       TIMESTAMP(6) WITH TIME ZONE,
    status          VARCHAR(20)                             NOT NULL,
    overtime_hours  DECIMAL(4, 2)                           NOT NULL,
    remarks         VARCHAR(255),
    CONSTRAINT pk_attendances PRIMARY KEY (id)
);

CREATE TABLE departments
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    department_name VARCHAR(100)                            NOT NULL,
    description     VARCHAR(500),
    CONSTRAINT pk_departments PRIMARY KEY (id)
);

CREATE TABLE employees
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    employee_code     VARCHAR(30)                             NOT NULL,
    first_name        VARCHAR(50)                             NOT NULL,
    last_name         VARCHAR(50)                             NOT NULL,
    gender            VARCHAR(20)                             NOT NULL,
    date_of_birth     date                                    NOT NULL,
    email             VARCHAR(100),
    phone             VARCHAR(20),
    address           VARCHAR(255),
    hire_date         date                                    NOT NULL,
    job_title         VARCHAR(100)                            NOT NULL,
    department_id     BIGINT,
    basic_salary      DECIMAL(12, 2)                          NOT NULL,
    employment_status VARCHAR(30)                             NOT NULL,
    CONSTRAINT pk_employees PRIMARY KEY (id)
);

CREATE TABLE leave_requests
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    employee_id    BIGINT                                  NOT NULL,
    leave_type     VARCHAR(30)                             NOT NULL,
    start_date     date                                    NOT NULL,
    end_date       date                                    NOT NULL,
    reason         VARCHAR(500)                            NOT NULL,
    status         VARCHAR(20)                             NOT NULL,
    reviewed_by_id BIGINT,
    reviewed_at    TIMESTAMP(6) WITH TIME ZONE,
    review_comment VARCHAR(500),
    CONSTRAINT pk_leave_requests PRIMARY KEY (id)
);

CREATE TABLE payrolls
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    employee_id   BIGINT                                  NOT NULL,
    payroll_month INTEGER                                 NOT NULL,
    payroll_year  INTEGER                                 NOT NULL,
    basic_salary  DECIMAL(10, 2)                          NOT NULL,
    allowances    DECIMAL(12, 2)                          NOT NULL,
    overtime_pay  DECIMAL(12, 2)                          NOT NULL,
    bonus         DECIMAL(12, 2)                          NOT NULL,
    deductions    DECIMAL(12, 2)                          NOT NULL,
    tax           DECIMAL(12, 2)                          NOT NULL,
    gross_salary  DECIMAL(12, 2)                          NOT NULL,
    net_salary    DECIMAL(12, 2)                          NOT NULL,
    status        VARCHAR(20)                             NOT NULL,
    calculated_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    paid_at       TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_payrolls PRIMARY KEY (id)
);

CREATE TABLE users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE             NOT NULL,
    username   VARCHAR(50)                             NOT NULL,
    email      VARCHAR(100)                            NOT NULL,
    password   VARCHAR(255)                            NOT NULL,
    role       VARCHAR(20)                             NOT NULL,
    active     BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

